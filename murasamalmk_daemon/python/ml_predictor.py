#!/usr/bin/env python3
"""
Murasama LMKd: Machine Learning Memory Pressure & Velocity Forecaster
This script implements online-learning models to predict memory spikes and pressure,
offering proactive recommendations to the Ada/SPARK daemon.
"""

import os
import json
import time
from typing import Dict, List, Any, Optional, Tuple, cast
import numpy as np
from sklearn.linear_model import SGDClassifier

# Constant configurations
TELEMETRY_PATH: str = "/usr/local/murasamaLMKd/EARU_data.dat"
PREDICTION_PATH: str = "/usr/local/murasamaLMKd/ml_prediction.txt"
MODEL_RETRAIN_INTERVAL: int = 5  # retrain/update model every 5 steps
HISTORY_MAX_LEN: int = 500       # maintain sliding buffer size of 500 samples

class OnlineMemoryPredictor:
    """
    An online machine learning predictor that trains incrementally on incoming telemetry data
    and forecasts future memory pressure levels.
    """
    def __init__(self) -> None:
        self.features_history: List[List[float]] = []
        self.labels_history: List[int] = []
        self.model: SGDClassifier = SGDClassifier(loss="log_loss", penalty="l2", alpha=0.01)
        self.classes: np.ndarray = np.array([1, 2, 3, 4, 5])
        self.is_trained: bool = False

    def add_sample(self, features: List[float], next_pressure: int) -> None:
        """
        Appends a new sample to the sliding window memory and incrementally trains the classifier.
        """
        self.features_history.append(features)
        self.labels_history.append(next_pressure)

        if len(self.features_history) > HISTORY_MAX_LEN:
            self.features_history.pop(0)
            self.labels_history.pop(0)

        # Train model with partial_fit to support streaming online learning
        if len(self.features_history) >= 10:
            X: np.ndarray = np.array([features])
            y: np.ndarray = np.array([next_pressure])
            try:
                self.model.partial_fit(X, y, classes=self.classes)
                self.is_trained = True
            except Exception as e:
                print(f"[ML ERROR] Failed to partially fit model: {e}")

    def predict_next(self, current_features: List[float]) -> Tuple[int, str]:
        """
        Predicts the next memory pressure level and assesses system risk.
        """
        if not self.is_trained:
            # Fallback to current level if model is not yet fit
            curr_level: int = int(current_features[2])
            return curr_level, "low"

        X: np.ndarray = np.array([current_features])
        try:
            pred_pressure: int = int(self.model.predict(X)[0])
            probs: np.ndarray = self.model.predict_proba(X)[0]
            # High pressure risk is based on the probability of pressure >= 4
            high_pressure_prob: float = float(np.sum(probs[3:]))
            risk_level: str = "high" if (pred_pressure >= 4 or high_pressure_prob > 0.4) else "low"
            return pred_pressure, risk_level
        except Exception as e:
            print(f"[ML ERROR] Prediction failed: {e}")
            curr_level = int(current_features[2])
            return curr_level, "low"

def parse_telemetry(path: str) -> Optional[Dict[str, Any]]:
    """
    Parses the telemetry JSON file generated by the Ada daemon.
    """
    if not os.path.exists(path):
        return None
    try:
        with open(path, "r") as f:
            data: Dict[str, Any] = cast(Dict[str, Any], json.load(f))
            return data
    except Exception:
        return None

def extract_features(data: Dict[str, Any]) -> List[float]:
    """
    Extracts numerical feature arrays from parsed JSON telemetry.
    """
    mem: Dict[str, Any] = cast(Dict[str, Any], data.get("memory", {}))
    thrashing: Dict[str, Any] = cast(Dict[str, Any], data.get("thrashing", {}))
    
    free_mb: float = float(mem.get("free_mb", 2048.0))
    wired_mb: float = float(mem.get("wired_mb", 4096.0))
    pressure_lvl: float = float(mem.get("pressure_level", 1.0))
    velocity: float = float(mem.get("velocity_mb_s", 0.0))
    
    pageins: float = float(thrashing.get("pageins_per_sec", 0.0))
    decomp: float = float(thrashing.get("decomp_per_sec", 0.0))
    
    return [free_mb, wired_mb, pressure_lvl, velocity, pageins, decomp]

def write_prediction(path: str, predicted_pressure: int, risk_level: str, target_pid: int) -> None:
    """
    Writes the predicted memory metrics and recommended action target to a flat file.
    """
    temp_path: str = path + ".tmp"
    try:
        with open(temp_path, "w") as f:
            f.write(f"predicted_pressure:{predicted_pressure}\n")
            f.write(f"risk_level:{risk_level}\n")
            f.write(f"target_pid:{target_pid}\n")
        os.replace(temp_path, path)
    except Exception as e:
        print(f"[ML ERROR] Failed to write predictions: {e}")

def main() -> None:
    print("[ML SERVICE] Online Memory Spike Forecasting Daemon Active.")
    predictor: OnlineMemoryPredictor = OnlineMemoryPredictor()
    
    last_features: Optional[List[float]] = None
    
    while True:
        time.sleep(1.0)
        
        telemetry: Optional[Dict[str, Any]] = parse_telemetry(TELEMETRY_PATH)
        if telemetry is None:
            continue
            
        try:
            features: List[float] = extract_features(telemetry)
            current_pressure: int = int(features[2])
            
            # Active App PID
            app_data: Dict[str, Any] = cast(Dict[str, Any], telemetry.get("active_app", {}))
            target_pid: int = int(app_data.get("pid", 0))

            # If we have a previous step, train the model to predict the current pressure
            # based on features of the previous step (1-second lag forecasting)
            if last_features is not None:
                predictor.add_sample(last_features, current_pressure)

            # Predict pressure level in the next timestep (1 second in the future)
            predicted_pressure, risk_level = predictor.predict_next(features)
            
            # Write recommendation to flat file for Ada daemon consumption
            write_prediction(PREDICTION_PATH, predicted_pressure, risk_level, target_pid)
            
            last_features = features
        except Exception as e:
            print(f"[ML SERVICE ERROR] Exception in main loop: {e}")

if __name__ == "__main__":
    main()
